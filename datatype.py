# data type in python 
#integer 
x=5 
print(x,type(x))
#string 
x="hello world"
print(x,type(x))

#float 
x=20.6 
print(x,type(x))

#list 
x=["apply","banana"]
print(x,type(x))

#set 
x=(10,20,30)
print(x,type(x))

#range 
x=range(6)
print(x,type(x))

#dictonaries 
x={"s":10,"j":20,"k":40}
print(x,type(x))

#tuple 
x={10,20,30}
print(x,type(x))

#complex 
x=1j 
print(x,type(x))

#frozen set 
x=frozenset({"apply","banaan","cherry"})
print(x,type(x))

#boolean 
x=True 

print(x,type(x))

#bytes 
x=b"hello world"
print(x,type(x))

#bytearray
x=bytearray(6)
print(x,type(x))

#memory view 
x=memoryview(bytes(5))
print(x,type(x))

x=None 
print(x,type(x))